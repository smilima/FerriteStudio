//! Rust code generation: the wiring module and handler stubs.
//!
//! The split mirrors C++Builder: the designer owns the generated wiring
//! (like the published section of a form's header), and the user owns the
//! events file, which the designer only appends to.

use std::fmt::Write as _;

use crate::model::{Form, HandlerRef};

/// Rust parameter list for a handler, after the form reference.
fn rust_params(h: &HandlerRef) -> String {
    h.args
        .iter()
        .map(|a| format!(", {}: {}", a.name, a.ty.rust_type()))
        .collect()
}

/// The generated `<form>_wiring.rs` module.
pub fn wiring_rs(form: &Form, slint_path: &str, events_module: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by Ferrite Studio from {slint_path}. Do not edit:");
    let _ = writeln!(out, "// the Form Designer rewrites this file every time the form is saved.\n");
    out.push_str("#![allow(unused_imports)]\n\n");
    out.push_str("use slint::ComponentHandle;\n\n");
    let _ = writeln!(out, "use crate::{events_module} as events;");
    let _ = writeln!(out, "use crate::{};\n", form.name);
    let _ = writeln!(out, "/// Connects every form event to its handler in `{events_module}.rs`.");
    let handlers = form.handlers();
    if handlers.is_empty() {
        let _ = writeln!(out, "pub fn connect(_form: &{}) {{}}", form.name);
        return out;
    }
    let _ = writeln!(out, "pub fn connect(form: &{}) {{", form.name);
    out.push_str("    let weak = form.as_weak();\n");
    for h in &handlers {
        let names: Vec<&str> = h.args.iter().map(|a| a.name).collect();
        let call_args: String = names.iter().map(|n| format!(", {n}")).collect();
        let _ = writeln!(out, "    form.on_{}({{", h.handler);
        out.push_str("        let weak = weak.clone();\n");
        let _ = writeln!(out, "        move |{}| {{", names.join(", "));
        out.push_str("            if let Some(form) = weak.upgrade() {\n");
        let _ = writeln!(out, "                events::{}(&form{});", h.handler, call_args);
        out.push_str("            }\n");
        out.push_str("        }\n");
        out.push_str("    });\n");
    }
    out.push_str("}\n");
    out
}

/// Initial contents of a user-owned `<form>_events.rs` file.
pub fn events_template(form: &Form) -> String {
    format!(
        "//! Event handlers for {name}.\n\
         //!\n\
         //! This file is yours. The Form Designer appends a stub when you create\n\
         //! an event handler and, like C++Builder, removes stubs you left empty\n\
         //! when the form is saved. Read and change controls through the form's\n\
         //! published properties, e.g. `form.get_edit1_text()`.\n\
         \n\
         #![allow(unused_imports)]\n\
         \n\
         use slint::{{ComponentHandle, Model, SharedString}};\n\
         \n\
         use crate::{name};\n",
        name = form.name
    )
}

/// The stub appended for a new handler.
pub fn stub(form: &Form, h: &HandlerRef) -> String {
    format!(
        "\n#[allow(unused_variables)]\npub fn {handler}(form: &{form}{params}) {{\n    // {control}.{callback}\n}}\n",
        handler = h.handler,
        form = form.name,
        params = rust_params(h),
        control = h.control,
        callback = h.callback,
    )
}

/// Byte range of a handler function, including the attribute line and the
/// blank line before it, plus whether its body is empty (only comments).
fn handler_span(source: &str, handler: &str) -> Option<(usize, usize, bool)> {
    let sig = format!("pub fn {handler}(");
    let mut search = 0;
    let start = loop {
        let at = search + source[search..].find(&sig)?;
        let line_start = source[..at].rfind('\n').map_or(0, |i| i + 1);
        if source[line_start..at].trim().is_empty() {
            break line_start;
        }
        search = at + sig.len();
    };
    let open = start + source[start..].find('{')?;
    let mut end = None;
    let mut empty = true;
    let mut pos = open + 1;
    let first_line_rest = source[pos..].split('\n').next().unwrap_or("");
    if !first_line_rest.trim().is_empty() {
        empty = false;
    }
    pos += first_line_rest.len();
    while pos < source.len() {
        pos += 1; // the newline
        let line = source[pos..].split('\n').next().unwrap_or("");
        let t = line.trim();
        if t == "}" && line.starts_with('}') {
            end = Some(pos + line.len());
            break;
        }
        if !(t.is_empty() || t.starts_with("//")) {
            empty = false;
        }
        pos += line.len();
    }
    let mut end = end?;
    if source[end..].starts_with('\n') {
        end += 1;
    }
    // Take the attribute line and one blank line above the signature.
    let mut start = start;
    let attr = "#[allow(unused_variables)]\n";
    if source[..start].ends_with(attr) {
        start -= attr.len();
    }
    if source[..start].ends_with("\n\n") {
        start -= 1;
    }
    Some((start, end, empty))
}

/// Result of bringing an events file in line with the form.
#[derive(Debug, Default, PartialEq)]
pub struct SyncResult {
    pub text: String,
    pub added: Vec<String>,
    pub removed: Vec<String>,
}

/// Appends stubs for handlers the file lacks and removes empty stubs for
/// handlers the form no longer uses. `known_handlers` lists every handler
/// name the designer ever created in this file, so user functions that
/// merely look like handlers are never touched.
pub fn sync_events(source: &str, form: &Form, known_handlers: &[String]) -> SyncResult {
    let mut text = source.to_string();
    let mut result = SyncResult::default();
    let used: Vec<&str> = form.handlers().iter().map(|h| h.handler).collect();

    for name in known_handlers {
        if used.contains(&name.as_str()) {
            continue;
        }
        if let Some((start, end, true)) = handler_span(&text, name) {
            text.replace_range(start..end, "");
            result.removed.push(name.clone());
        }
    }
    for h in form.handlers() {
        if handler_span(&text, h.handler).is_none() {
            if !text.ends_with('\n') {
                text.push('\n');
            }
            text.push_str(&stub(form, &h));
            result.added.push(h.handler.to_string());
        }
    }
    result.text = text;
    result
}

/// Byte offset just inside a handler's body, where the caret goes after
/// double-clicking a control: the start of the line after the signature.
pub fn handler_body_offset(source: &str, handler: &str) -> Option<usize> {
    let (start, _, _) = handler_span(source, handler)?;
    let sig = source[start..].find(&format!("pub fn {handler}("))? + start;
    let open = sig + source[sig..].find('{')?;
    let nl = open + source[open..].find('\n')? + 1;
    // Place the caret after the indentation of the first body line.
    let indent = source[nl..].chars().take_while(|c| *c == ' ').count();
    Some(nl + indent)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn form_with_handlers() -> Form {
        let mut f = Form::new("MainForm");
        let b = f.add_control("Button", 0, 0).unwrap();
        f.ensure_handler(b, "clicked").unwrap();
        let e = f.add_control("LineEdit", 0, 40).unwrap();
        f.ensure_handler(e, "edited").unwrap();
        f
    }

    #[test]
    fn wiring_connects_every_handler() {
        let f = form_with_handlers();
        let w = wiring_rs(&f, "ui/main_form.slint", "main_form_events");
        assert!(w.contains("form.on_button1_clicked({"));
        assert!(w.contains("move |text| {"));
        assert!(w.contains("events::edit1_edited(&form, text);"));
        let empty = wiring_rs(&Form::new("MainForm"), "ui/main_form.slint", "main_form_events");
        assert!(empty.contains("pub fn connect(_form: &MainForm) {}"));
    }

    #[test]
    fn stubs_are_appended_once_and_empty_ones_removed() {
        let mut f = form_with_handlers();
        let src = events_template(&f);
        let r = sync_events(&src, &f, &[]);
        assert_eq!(r.added, vec!["button1_clicked", "edit1_edited"]);
        assert!(r.text.contains("pub fn edit1_edited(form: &MainForm, text: slint::SharedString) {"));
        let again = sync_events(&r.text, &f, &[]);
        assert!(again.added.is_empty());
        assert_eq!(again.text, r.text);

        // The user writes code in one handler, then deletes both controls.
        let edited = r.text.replace("    // edit1.edited\n", "    println!(\"{text}\");\n");
        f.controls.clear();
        let known = vec!["button1_clicked".to_string(), "edit1_edited".to_string()];
        let cleaned = sync_events(&edited, &f, &known);
        assert_eq!(cleaned.removed, vec!["button1_clicked"]);
        assert!(!cleaned.text.contains("button1_clicked"));
        assert!(cleaned.text.contains("pub fn edit1_edited"));
        assert!(cleaned.text.starts_with(&events_template(&Form::new("MainForm"))));
    }

    #[test]
    fn caret_lands_inside_the_new_handler() {
        let f = form_with_handlers();
        let r = sync_events(&events_template(&f), &f, &[]);
        let off = handler_body_offset(&r.text, "button1_clicked").unwrap();
        assert!(r.text[off..].starts_with("// button1.clicked"));
    }
}
